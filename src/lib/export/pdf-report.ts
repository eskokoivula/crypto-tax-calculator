import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';
import { CHAIN_NAMES, FINNISH_TAX } from '@/types';
import type { Transaction, TaxSummary } from '@/types';
import { formatEur, formatDate } from '@/lib/utils';
import type { UserInfo } from './types';

/**
 * Generate a full PDF tax report covering all transactions and a summary.
 */
export function generateTaxReport(
  transactions: Transaction[],
  summary: TaxSummary,
  userInfo: UserInfo,
  taxYear: number,
): Uint8Array {
  const doc = new jsPDF();

  // -----------------------------------------------------------------------
  // Page 1: Cover + Summary
  // -----------------------------------------------------------------------
  doc.setFontSize(20);
  doc.text('Kryptoveroilmoitus / Crypto Tax Report', 14, 24);

  doc.setFontSize(14);
  doc.text(`Verovuosi ${taxYear}`, 14, 34);

  doc.setFontSize(10);
  doc.text(`Nimi: ${userInfo.name}`, 14, 46);
  doc.text(`Henkilotunnus: ${userInfo.henkilotunnus}`, 14, 52);
  doc.text(`Luotu: ${new Date().toLocaleDateString('fi-FI')}`, 14, 58);

  // Summary table
  const { CAPITAL_GAINS_RATE_LOW, CAPITAL_GAINS_RATE_HIGH, CAPITAL_GAINS_THRESHOLD } =
    FINNISH_TAX;

  const lowerBracketAmount = Math.min(
    Math.max(summary.taxableGainsEur, 0),
    CAPITAL_GAINS_THRESHOLD,
  );
  const upperBracketAmount = Math.max(
    summary.taxableGainsEur - CAPITAL_GAINS_THRESHOLD,
    0,
  );
  const lowerTax = lowerBracketAmount * CAPITAL_GAINS_RATE_LOW;
  const upperTax = upperBracketAmount * CAPITAL_GAINS_RATE_HIGH;

  const summaryRows = [
    ['Realisoituneet voitot / Realized Gains', formatEur(summary.totalRealizedGainsEur)],
    ['Realisoimattomat voitot / Unrealized Gains', formatEur(summary.totalUnrealizedGainsEur)],
    ['Tulot / Income', formatEur(summary.totalIncomeEur)],
    ['Kulut ja palkkiot / Fees & Costs', formatEur(summary.totalFeesEur)],
    ['Nettopositio / Net Position', formatEur(summary.netPositionEur)],
    ['', ''],
    ['Verotettava paaomatulo / Taxable Capital Income', formatEur(summary.taxableGainsEur)],
    [
      `  30 % vero (0 - ${CAPITAL_GAINS_THRESHOLD.toLocaleString('fi-FI')} EUR)`,
      formatEur(lowerTax),
    ],
    [
      `  34 % vero (> ${CAPITAL_GAINS_THRESHOLD.toLocaleString('fi-FI')} EUR)`,
      formatEur(upperTax),
    ],
    ['Arvioitu vero / Estimated Tax', formatEur(summary.estimatedTaxEur)],
  ];

  autoTable(doc, {
    startY: 66,
    head: [['', '']],
    body: summaryRows,
    theme: 'plain',
    styles: { fontSize: 10, cellPadding: 2 },
    columnStyles: {
      0: { cellWidth: 120 },
      1: { cellWidth: 50, halign: 'right' },
    },
    didParseCell(data) {
      // Bold the total tax row
      if (data.row.index === summaryRows.length - 1) {
        data.cell.styles.fontStyle = 'bold';
      }
    },
  });

  // -----------------------------------------------------------------------
  // Page 2+: Transaction Details
  // -----------------------------------------------------------------------
  doc.addPage();
  doc.setFontSize(14);
  doc.text('Tapahtumat / Transactions', 14, 18);

  const txRows = transactions.map((tx) => {
    const effectiveCategory = tx.categoryOverride ?? tx.category;
    return [
      formatDate(tx.timestamp),
      tx.tokenSymbol,
      effectiveCategory,
      formatEur(tx.valueEur),
      tx.costBasisEur != null ? formatEur(tx.costBasisEur) : '-',
      tx.gainLossEur != null ? formatEur(tx.gainLossEur) : '-',
      effectiveCategory,
    ];
  });

  autoTable(doc, {
    startY: 24,
    head: [['Pvm', 'Token', 'Tyyppi', 'Arvo EUR', 'Hankintahinta', 'Voitto/Tappio', 'Kategoria']],
    body: txRows,
    theme: 'striped',
    styles: { fontSize: 7, cellPadding: 1.5 },
    headStyles: { fillColor: [55, 65, 81] },
  });

  // -----------------------------------------------------------------------
  // Final page: Notes
  // -----------------------------------------------------------------------
  doc.addPage();
  doc.setFontSize(14);
  doc.text('Huomautukset / Notes', 14, 18);

  doc.setFontSize(9);
  const notes = [
    'Generated by CryptoTax Finland.',
    'This is an unofficial document. Consult a tax professional.',
    'Currency: EUR (converted from USD using ECB daily rates).',
    'Cost basis method: FIFO (First In, First Out).',
    `Tax year: ${taxYear}`,
    `Total transactions: ${transactions.length}`,
    `Chains: ${uniqueChains(transactions).join(', ')}`,
  ];
  notes.forEach((note, i) => {
    doc.text(`- ${note}`, 14, 28 + i * 6);
  });

  return new Uint8Array(doc.output('arraybuffer'));
}

// ---------------------------------------------------------------------------
// Helpers
// ---------------------------------------------------------------------------

function uniqueChains(transactions: Transaction[]): string[] {
  const chains = new Set(transactions.map((tx) => CHAIN_NAMES[tx.chain] ?? tx.chain));
  return Array.from(chains);
}
